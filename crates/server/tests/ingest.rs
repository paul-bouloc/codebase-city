#[tokio::test]
async fn every_limit_stops_the_ingestion() {
    let files: &[(&str, &[u8])] = &[
        ("src/a.ts", b"export const a = 'some content'\n"),
        ("src/b.ts", b"export const b = 'some content'\n"),
        ("src/c.ts", b"export const c = 'some content'\n"),
    ];
    let cases = [
        (
            Limits {
                archive_bytes: 10,
                ..Limits::default()
            },
            IngestError::ArchiveTooLarge { limit: 10 },
        ),
        (
            Limits {
                unpacked_bytes: 1000,
                ..Limits::default()
            },
            IngestError::UnpackedTooLarge { limit: 1000 },
        ),
        (
            Limits {
                kept_bytes: 40,
                ..Limits::default()
            },
            IngestError::KeptTooLarge { limit: 40 },
        ),
        (
            Limits {
                kept_files: 2,
                ..Limits::default()
            },
            IngestError::TooManyFiles { limit: 2 },
        ),
        (
            Limits {
                entries: 3,
                ..Limits::default()
            },
            IngestError::TooManyEntries { limit: 3 },
        ),
    ];
    for (limits, expected) in cases {
        let error = ingest_files(files, &limits).await.unwrap_err();
        assert_eq!(error, expected);
    }
    // The same archive passes with the default limits.
    assert!(ingest_files(files, &Limits::default()).await.is_ok());
}

#[tokio::test]
async fn a_download_that_drags_on_is_stopped() {
    let content: String = (0..2000)
        .map(|i| format!("export const v{i} = {}\n", i * 7919 % 10007))
        .collect();
    let archive = tarball(&[("src/a.ts", content.as_bytes())]);
    // 64-byte chunks, 30 ms apart: far more than the 100 ms allowed.
    assert!(archive.len() > 64 * 20, "{} bytes", archive.len());
    let limits = Limits {
        download: Duration::from_millis(100),
        ..Limits::default()
    };
    let error = serve(
        Reply::SlowArchive(archive, Duration::from_millis(30)),
        &limits,
    )
    .await
    .unwrap_err();
    assert_eq!(
        error,
        IngestError::DownloadTimeout {
            limit: Duration::from_millis(100)
        }
    );
}

#[tokio::test]
async fn a_slow_reader_is_not_a_slow_download() {
    // 500 small files make the reader report its progress, then a file
    // that does not compress, so the archive is still arriving
    let mut seed = 1u32;
    let noise: String = (0..40_000)
        .map(|_| {
            seed = seed.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
            char::from(b'a' + (seed >> 24) as u8 % 26)
        })
        .collect();
    let names: Vec<String> = (0..500).map(|i| format!("src/f{i}.ts")).collect();
    let mut files: Vec<(&str, &[u8])> = names
        .iter()
        .map(|name| (name.as_str(), b"export const a = 1\n".as_slice()))
        .collect();
    files.push(("src/noise.ts", noise.as_bytes()));

    let github = FakeGithub::start().await;
    github.on(
        &tarball_path(),
        [Reply::SlowArchive(tarball(&files), Duration::ZERO)],
    );
    // The reader stalls for 1 s at its first progress report, with the
    // channel full behind it; the network alone takes far less than 500 ms
    let on_progress = Arc::new(|progress| {
        if let Progress::Reading { kept: 500, .. } = progress {
            std::thread::sleep(Duration::from_secs(1));
        }
    });
    let limits = Limits {
        download: Duration::from_millis(500),
        ..Limits::default()
    };
    let ingested = ingest(&github.client(None), &repo(), SHA, &limits, on_progress)
        .await
        .unwrap();
    assert_eq!(ingested.files.len(), 501);
}

