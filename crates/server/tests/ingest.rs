#[tokio::test]
async fn progress_is_reported() {
    let github = FakeGithub::start().await;
    github.on(
        &tarball_path(),
        [
            Reply::text(429, "rate-limited"),
            Reply::Archive(tarball(&[
                ("src/a.ts", b"export {}\n"),
                ("logo.png", b"png"),
            ])),
        ],
    );
    let events = Arc::new(Mutex::new(Vec::new()));
    let recorded = Arc::clone(&events);
    let on_progress = Arc::new(move |progress| recorded.lock().unwrap().push(progress));

    ingest(
        &github.client(None),
        &repo(),
        SHA,
        &Limits::default(),
        on_progress,
    )
    .await
    .unwrap();

    let events = events.lock().unwrap();
    assert_eq!(
        events.first(),
        Some(&Progress::WaitingForGithub(Duration::from_millis(10)))
    );
    assert!(
        events
            .iter()
            .any(|event| matches!(event, Progress::Downloading { bytes } if *bytes > 0))
    );
    // Download and reading run side by side: only their own order is fixed.
    let last_reading = events
        .iter()
        .rfind(|event| matches!(event, Progress::Reading { .. }));
    assert_eq!(
        last_reading,
        Some(&Progress::Reading {
            kept: 1,
            skipped: 1
        })
    );
}
