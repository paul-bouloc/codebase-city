//! Parsing of small hand-written files, one or two per dialect, in
//! `tests/fixtures/parsing/`.

#![allow(clippy::unwrap_used)]

use analyzer::files::Language;
use analyzer::lang::{Parsed, parse};
use model::EdgeKind::{Dynamic, Import, Lazy, Reexport};
use model::SymbolKind::{self, Class, Constant, Enum, Function, Interface, Type};

fn parse_text(name: &str, content: &str) -> Parsed {
    parse(name, Language::of(name), content.as_bytes()).unwrap()
}

fn fixture(name: &str) -> Parsed {
    let path = format!(
        "{}/tests/fixtures/parsing/{name}",
        env!("CARGO_MANIFEST_DIR")
    );
    parse_text(name, &std::fs::read_to_string(path).unwrap())
}

fn symbols(parsed: &Parsed) -> Vec<(&str, SymbolKind, u32)> {
    parsed
        .symbols
        .iter()
        .map(|symbol| (symbol.name.as_str(), symbol.kind, symbol.line))
        .collect()
}

#[test]
fn typescript_complexity_counts_each_decision_once() {
    let parsed = fixture("complexity.ts");
    assert_eq!(parsed.complexity, 14);
    assert_eq!(
        parsed.header.as_deref(),
        Some("// Every decision point is marked with what it adds; the file starts at 1.")
    );
}

