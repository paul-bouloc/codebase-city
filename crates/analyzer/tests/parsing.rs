#[test]
fn a_file_with_only_a_license_has_no_header() {
    let parsed = parse_text("a.ts", "// Copyright 2024 Acme\n\nexport const a = 1\n");
    assert_eq!(parsed.header, None);
    let parsed = parse_text(
        "a.go",
        "// Code generated by stringer. DO NOT EDIT.\n\npackage a\n",
    );
    assert_eq!(parsed.header, None);
}

#[test]
fn prose_that_looks_like_a_directive_is_a_header() {
    for header in [
        "// Global state shared by the store and the view.",
        "// Validates the license key entered by the user.",
    ] {
        let parsed = parse_text("a.ts", &format!("{header}\n\nexport const a = 1\n"));
        assert_eq!(parsed.header.as_deref(), Some(header));
    }
    // An encoding declaration only counts on the first two lines (PEP 263)
    let parsed = parse_text(
        "a.py",
        "#!/usr/bin/env python\n\n# Decoding: turns raw frames into packets.\nimport os\n",
    );
    assert_eq!(
        parsed.header.as_deref(),
        Some("# Decoding: turns raw frames into packets.")
    );
}

#[test]
fn go_directives_are_not_headers() {
    let parsed = parse_text(
        "a.go",
        "//go:generate stringer -type=Kind\n\n// Package a does b.\npackage a\n",
    );
    assert_eq!(parsed.header.as_deref(), Some("// Package a does b."));
}

#[test]
fn a_python_wildcard_case_is_not_a_decision() {
    let parsed = parse_text(
        "a.py",
        "match x:\n    case 1:\n        pass\n    case _ if y:\n        pass\n    case _:\n        pass\n",
    );
    // `case 1`, the guarded case and its guard, and nothing for `case _`
    assert_eq!(parsed.complexity, 4);
}

#[test]
fn the_doc_of_a_declaration_is_not_a_header() {
    let parsed = parse_text(
        "add.ts",
        "/** Adds two numbers. */\nexport function add() {}\n",
    );
    assert_eq!(parsed.header, None);

    let parsed = parse_text(
        "add.ts",
        "// Arithmetic helpers.\n\n/** Adds two numbers. */\nexport function add() {}\n",
    );
    assert_eq!(parsed.header.as_deref(), Some("// Arithmetic helpers."));

    // Right above the imports, it describes the file
    for first in ["import { b } from './b'", "const b = require('./b')"] {
        let parsed = parse_text("a.js", &format!("// Wires a to b.\n{first}\n"));
        assert_eq!(parsed.header.as_deref(), Some("// Wires a to b."));
    }
}

#[test]
fn empty_comments_and_tool_comments_are_not_headers() {
    let parsed = parse_text("a.ts", "//\n\nexport const a = 1\n");
    assert_eq!(parsed.header, None);
    let parsed = parse_text(
        "vite-env.d.ts",
        "/// <reference types=\"vite/client\" />\n\n// Types for the env.\n\nexport {}\n",
    );
    assert_eq!(parsed.header.as_deref(), Some("// Types for the env."));
}

#[test]
fn a_comment_after_the_first_statement_is_not_a_header() {
    let parsed = parse_text("a.py", "import os\n\n# Not a header.\n");
    assert_eq!(parsed.header, None);
}

#[test]
fn broken_files_are_still_measured() {
    let parsed = parse_text(
        "broken.ts",
        "export function broken( {\n  if (a) {\n    return b ? 1 : 2\n",
    );
    assert!(parsed.complexity >= 2);

    let parsed = parse_text("broken.py", "def f(:\n    if x:\n        pass\n");
    assert!(parsed.complexity >= 1);
}

#[test]
fn a_broken_export_has_no_nameless_symbol() {
    let parsed = parse_text(
        "broken.js",
        "exports. = function json() {}\nmodule.exports.= '1.0'\nmodule.exports = { : 1, () {} }\n",
    );
    assert!(
        parsed.symbols.iter().all(|symbol| !symbol.name.is_empty()),
        "{:?}",
        parsed.symbols
    );
}

#[test]
fn a_type_and_a_value_may_share_a_name() {
    let parsed = parse_text(
        "user.ts",
        "export const User = z.object({})\nexport type User = z.infer<typeof User>\n",
    );
    assert_eq!(symbols(&parsed), [("User", Constant, 1), ("User", Type, 2)]);
}

#[test]
fn invalid_utf8_does_not_stop_parsing() {
    let content = b"// caf\xe9\n\nexport const a = 1\n";
    let parsed = parse("a.js", Language::JavaScript, content).unwrap();
    assert_eq!(parsed.header.as_deref(), Some("// caf\u{fffd}"));
    assert_eq!(parsed.symbols.len(), 1);
}

