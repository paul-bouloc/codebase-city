/// Imports of npm packages, not in the repository.
const EXTERNAL_IMPORTS: u32 = 4;

/// Imports that could not be resolved.
const UNRESOLVED_IMPORTS: u32 = 1;

/// Islands per row of the sample's archipelago.
const ISLANDS_PER_ROW: u32 = 4;

/// A simple archipelago, in tenths of a unit: each island a near-square
/// grid of its folder's files, a 0.9 u margin, at least 10 × 6.6 u, the
/// islands in rows of four with 9 u of water between them. The files fill
/// each grid from its north-west lot.
fn layout() -> Layout {
    const LOT: u32 = 20;
    const MARGIN: u32 = 9;
    const CHANNEL: u32 = 90;
    let mut layout = Layout::default();
    let mut lots = vec![(0, 0); FILES.len()];
    let (mut x, mut y, mut row_height) = (0, 0, 0);
    for island in 0..ISLANDS {
        let files: Vec<usize> = (0..FILES.len())
            .filter(|&file| FILES[file].0 == island)
            .collect();
        let count = u32::try_from(files.len()).unwrap();
        let columns = count.isqrt() + u32::from(count.isqrt().pow(2) < count);
        let rows = count.div_ceil(columns);
        let width = (columns * LOT + 2 * MARGIN).max(100);
        let height = (rows * LOT + 2 * MARGIN).max(66);
        if island > 0 && island % ISLANDS_PER_ROW == 0 {
            (x, y) = (0, y + row_height + CHANNEL);
            row_height = 0;
        }
        layout.islands.x.push(x);
        layout.islands.y.push(y);
        layout.islands.width.push(width);
        layout.islands.height.push(height);
        let (grid_x, grid_y) = (x + MARGIN, y + MARGIN);
        layout.grids.dir.push(island);
        layout.grids.x.push(grid_x);
        layout.grids.y.push(grid_y);
        layout.grids.columns.push(columns);
        layout.grids.rows.push(rows);
        // As the analyzer tells it: a language it does not read wins over tests
        let scope = |file: usize| {
            SCOPES
                .iter()
                .find(|&&(row, _)| row as usize == file)
                .map_or(Scope::Source, |&(_, scope)| scope)
        };
        let unanalyzed = files
            .iter()
            .filter(|&&file| !ANALYZED.contains(&FILES[file].2))
            .count();
        let tests = files
            .iter()
            .filter(|&&file| matches!(scope(file), Scope::Test | Scope::Fixture))
            .count();
        layout.grids.nature.push(if unanalyzed * 2 > files.len() {
            ParcelNature::Unanalyzed
        } else if tests * 2 > files.len() {
            ParcelNature::Tests
        } else {
            ParcelNature::Normal
        });
        for (lot, &file) in (0..).zip(&files) {
            let (column, row) = (lot % columns, lot / columns);
            lots[file] = (
                grid_x + column * LOT + LOT / 2,
                grid_y + (rows - 1 - row) * LOT + LOT / 2,
            );
        }
        layout.width = layout.width.max(x + width);
        layout.height = layout.height.max(y + height);
        x += width + CHANNEL;
        row_height = row_height.max(height);
    }
    layout.parcels = Parcels::default();
    layout.lots = Lots {
        x: lots.iter().map(|lot| lot.0).collect(),
        y: lots.iter().map(|lot| lot.1).collect(),
    };
    layout
}

fn strings(values: impl IntoIterator<Item = &'static str>) -> Vec<String> {
    values.into_iter().map(str::to_owned).collect()
}

fn sample() -> AnalysisResult {
    let imports_resolved = u32::try_from(EDGES.len()).unwrap();
    AnalysisResult {
        format_version: FORMAT_VERSION,
        analyzer_version: "0.1.0".to_owned(),
        repo: Repo {
            owner: "acme".to_owned(),
            name: "harbor".to_owned(),
        },
        sha: "3f2c9a1e8b7d6c5f4a3b2c1d0e9f8a7b6c5d4e3f".to_owned(),
        dirs: Dirs {
            parent: DIRS.iter().map(|dir| dir.0).collect(),
            name: strings(DIRS.iter().map(|dir| dir.1)),
            island: (0..ISLANDS).map(Some).collect(),
        },
        languages: strings(LANGUAGES.iter().copied()),
        files: Files {
            dir: FILES.iter().map(|file| file.0).collect(),
            name: strings(FILES.iter().map(|file| file.1)),
            language: FILES.iter().map(|file| file.2).collect(),
            lines: FILES.iter().map(|file| file.3).collect(),
            complexity: FILES.iter().map(|file| file.4).collect(),
            generated: FILES.iter().map(|file| file.5).collect(),
            header: (0..FILES.len())
                .map(|row| {
                    HEADERS
                        .iter()
                        .find(|header| header.0 as usize == row)
                        .map(|header| header.1.to_owned())
                })
                .collect(),
            scope: (0..FILES.len())
                .map(|row| {
                    SCOPES
                        .iter()
                        .find(|scope| scope.0 as usize == row)
                        .map_or(Scope::Source, |scope| scope.1)
                })
                .collect(),
            barrel: (0..FILES.len()).map(|row| row == BARREL as usize).collect(),
            dependents: REACH.iter().map(|reach| reach.map(|r| r.0)).collect(),
            dependencies: REACH.iter().map(|reach| reach.map(|r| r.1)).collect(),
        },
        symbols: Symbols {
            file: SYMBOLS.iter().map(|symbol| symbol.0).collect(),
            name: strings(SYMBOLS.iter().map(|symbol| symbol.1)),
            kind: SYMBOLS.iter().map(|symbol| symbol.2).collect(),
            line: SYMBOLS.iter().map(|symbol| symbol.3).collect(),
        },
        edges: Edges {
            from: EDGES.iter().map(|edge| edge.0).collect(),
            to: EDGES.iter().map(|edge| Some(edge.1)).collect(),
            to_dir: vec![None; EDGES.len()],
            kind: EDGES.iter().map(|edge| edge.2).collect(),
            confidence: EDGES.iter().map(|edge| edge.3).collect(),
        },
        roles: Roles {
            entries: Entries {
                file: vec![Some(2)],
                dir: vec![None],
                reasons: vec![vec![
                    EntryReason::PackageMain,
                    EntryReason::ConventionalName,
                ]],
                command: vec![None],
            },
            // As the analyzer ranks them: `events.ts` and `store.ts` tie, both
            // imported from `core` alone, so the path decides. `app.ts` has
            // one user, `main.ts`, as few as the 20th percentile allows
            foundations: Ranked {
                file: vec![Some(8), Some(7), Some(6), Some(5)],
                dir: vec![None; 4],
                count: vec![11, 9, 7, 7],
            },
            conductors: Ranked {
                file: vec![Some(2), Some(3), Some(13)],
                dir: vec![None; 3],
                count: vec![12, 11, 9],
            },
        },
        islands: Islands {
            dir: (0..ISLANDS).collect(),
            layer: LAYERS.to_vec(),
        },
        links: Links {
            from: LINKS.iter().map(|link| link.0).collect(),
            to: LINKS.iter().map(|link| link.1).collect(),
            imports: LINKS.iter().map(|link| link.2).collect(),
            upward: vec![0; LINKS.len()],
        },
        cycles: Cycles {
            members: vec![vec![5, 6], vec![9, 12]],
            shortest: vec![vec![5, 6], vec![9, 12]],
        },
        layout: layout(),
        stats: Stats {
            ignored: Ignored {
                vendored: 3,
                minified: 1,
                binary: 2,
                deep: 1,
            },
            imports_total: imports_resolved + EXTERNAL_IMPORTS + UNRESOLVED_IMPORTS,
            imports_resolved,
            imports_external: EXTERNAL_IMPORTS,
        },
    }
}

#[test]
fn the_sample_is_valid() {
    assert_eq!(sample().validate(), Ok(()));
}

#[test]
fn a_result_survives_a_json_round_trip() {
    let json = serde_json::to_string(&sample()).unwrap();
    let decoded: AnalysisResult = serde_json::from_str(&json).unwrap();
    assert_eq!(decoded, sample());
}

#[test]
fn json_uses_the_names_of_the_generated_types() {
    let json = serde_json::to_value(sample()).unwrap();
    assert_eq!(json["formatVersion"], FORMAT_VERSION);
    assert_eq!(json["stats"]["importsResolved"], 26);
    assert_eq!(json["stats"]["importsExternal"], 4);
    assert!(json["edges"]["toDir"][0].is_null());
    assert_eq!(json["edges"]["kind"][3], "lazy");
    assert_eq!(json["edges"]["confidence"][19], "likely");
    assert!(json["files"]["complexity"][0].is_null());
    assert!(json["files"]["header"][0].is_null());
    assert_eq!(json["symbols"]["kind"][6], "interface");
    assert!(json["files"]["dependents"][0].is_null());
    assert_eq!(json["roles"]["entries"]["reasons"][0][0], "packageMain");
    assert!(json["islands"]["layer"][0].is_null());
    assert_eq!(json["dirs"]["island"][2], 2);
    assert_eq!(json["cycles"]["shortest"][1][0], 9);
    assert_eq!(json["layout"]["grids"]["columns"][2], 3);
    assert_eq!(json["layout"]["lots"]["x"][0], 19);
}

#[test]
fn export_sample() {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../web/src/data/generated");
    // ts-rs may not have created the folder yet: tests run in parallel
    std::fs::create_dir_all(&dir).unwrap();
    let mut json = serde_json::to_string_pretty(&sample()).unwrap();
    json.push('\n');
    std::fs::write(dir.join("sample-result.json"), json).unwrap();
}
